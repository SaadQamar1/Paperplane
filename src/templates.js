import { convertToExcalidrawElements } from "@excalidraw/excalidraw";
const box = (id, x, y, width, height, text, backgroundColor = "#e9e5ff") => ({
  type: "rectangle",
  id,
  x,
  y,
  width,
  height,
  strokeColor: "#514a6b",
  backgroundColor,
  fillStyle: "solid",
  strokeWidth: 1.5,
  roughness: 1,
  roundness: { type: 3 },
  label: { text, fontSize: 20, fontFamily: 2 },
});
const text = (x, y, value, fontSize = 26) => ({
  type: "text",
  x,
  y,
  text: value,
  fontSize,
  fontFamily: 2,
  strokeColor: "#33313e",
});
const arrow = (x, y, width, height = 0) => ({
  type: "arrow",
  x,
  y,
  width,
  height,
  points: [
    [0, 0],
    [width, height],
  ],
  endArrowhead: "arrow",
  strokeColor: "#7c7790",
  strokeWidth: 2,
  roughness: 1,
});
