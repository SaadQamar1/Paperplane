export function makeBoard(template = templates[0]) {
  return {
    id: crypto.randomUUID(),
    title: template.id === "blank" ? "Untitled board" : template.name,
    updated: Date.now(),
    created: Date.now(),
    favorite: false,
    color: template.color,
    elements: convertToExcalidrawElements(template.shapes),
    appState: { viewBackgroundColor: "#ffffff" },
    files: {},
  };
}
